/**
 * Application entry point for the Hotel Booking System.
 * Goal: Establish a clear and predictable starting point for the Hotel Booking application by
 * demonstrating how a Java program begins execution and produces console output.
 *
 * @author Book My Stay App
 * @version 1.0
 */
public class UseCase1HotelBookingApp {

    /**
     * The main method is the entry point of every standalone Java application.
     * The JVM looks specifically for the method signature: public static void main(String[] args).
     *
     * @param args Command-line arguments passed to the application.
     */
    public static void main(String[] args) {
        // Console Output - System.out.println() is used to send text output to the console.
        System.out.println("Welcome to the Hotel Booking System!");
        System.out.println("Application: Hotel Booking System v1.0");
    }
}
